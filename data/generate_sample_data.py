"""
Sample Network Traffic Dataset Generator
Generates a realistic synthetic network traffic dataset based on CIC-IDS2017 flow feature schema.
DISCLAIMER: All records generated by this script are synthetic and designed strictly for
academic testing, benchmarking, and ML model training demonstrations.
"""

import os
import numpy as np
import pandas as pd


def generate_synthetic_network_data(n_samples: int = 4500, random_state: int = 42) -> pd.DataFrame:
    """
    Generate synthetic network traffic flow dataset with realistic distributions.
    
    Categories:
    - BENIGN: Normal browsing, streaming, DNS resolution, regular TCP/UDP sessions.
    - PortScan: Rapid single/double packet probes to multiple destination ports, high SYN/RST, ACK=0.
    - DDoS: Enormous packet rate, high SYN or UDP volume targeting port 80/443.
    - FTP-Patator: Repeated login attempts to port 21, low byte variance.
    - SSH-Patator: Repeated authentication attempts to port 22, short bursts.
    - DoS-Hulk: Heavy HTTP request floods on port 80, irregular header lengths.
    - Web Attack - SQL Injection: Malicious URL queries on port 80/8080, large forward payload size.
    - Botnet: Low-volume, periodic beaconing on non-standard ports (e.g., 6667, 8443).
    """
    np.random.seed(random_state)
    
    classes_ratio = {
        'BENIGN': int(n_samples * 0.52),
        'PortScan': int(n_samples * 0.12),
        'DDoS': int(n_samples * 0.12),
        'FTP-Patator': int(n_samples * 0.06),
        'SSH-Patator': int(n_samples * 0.05),
        'DoS-Hulk': int(n_samples * 0.06),
        'Web Attack - SQL Injection': int(n_samples * 0.04),
        'Botnet': int(n_samples * 0.03)
    }
    
    dfs = []
    
    for label, count in classes_ratio.items():
        if count <= 0:
            continue
            
        if label == 'BENIGN':
            # Normal mix of HTTP (80), HTTPS (443), DNS (53), Ephemeral ports
            ports = np.random.choice([80, 443, 53, 8080, 123, 49152 + np.random.randint(0, 1000)], size=count, p=[0.25, 0.45, 0.20, 0.05, 0.03, 0.02])
            proto = np.where(ports == 53, 17, np.random.choice([6, 17], size=count, p=[0.92, 0.08]))
            duration = np.random.exponential(scale=250000, size=count) + 500  # microseconds
            fwd_pkts = np.random.poisson(lam=12, size=count) + 2
            bwd_pkts = np.random.poisson(lam=14, size=count) + 2
            fwd_len_mean = np.random.normal(loc=280, scale=80, size=count).clip(40, 1400)
            bwd_len_mean = np.random.normal(loc=650, scale=200, size=count).clip(40, 1460)
            syn_flags = np.random.choice([0, 1], size=count, p=[0.3, 0.7])
            ack_flags = np.random.choice([1, 0], size=count, p=[0.95, 0.05])
            rst_flags = np.random.choice([0, 1], size=count, p=[0.97, 0.03])
            iat_mean = duration / (fwd_pkts + bwd_pkts)
            
        elif label == 'PortScan':
            # Probing multiple common and random ports
            ports = np.random.choice([21, 22, 23, 25, 80, 110, 139, 443, 445, 1433, 3306, 3389, 8080], size=count)
            proto = np.full(count, 6) # TCP
            duration = np.random.uniform(50, 4000, size=count) # Extremely short
            fwd_pkts = np.random.choice([1, 2, 3], size=count, p=[0.75, 0.20, 0.05])
            bwd_pkts = np.random.choice([0, 1], size=count, p=[0.85, 0.15])
            fwd_len_mean = np.full(count, 44.0) # Just TCP SYN header
            bwd_len_mean = np.random.choice([0.0, 40.0], size=count, p=[0.85, 0.15])
            syn_flags = np.full(count, 1) # SYN flood / probe
            ack_flags = np.full(count, 0) # No handshake completion
            rst_flags = np.random.choice([0, 1], size=count, p=[0.4, 0.6]) # Reset received
            iat_mean = np.random.uniform(10, 500, size=count)
            
        elif label == 'DDoS':
            # Flooding port 80 or 443
            ports = np.random.choice([80, 443], size=count, p=[0.7, 0.3])
            proto = np.random.choice([6, 17], size=count, p=[0.8, 0.2])
            duration = np.random.exponential(scale=1200000, size=count) + 50000
            fwd_pkts = np.random.poisson(lam=85, size=count) + 30
            bwd_pkts = np.random.poisson(lam=5, size=count) + 1  # Server overwhelmed
            fwd_len_mean = np.random.normal(loc=120, scale=30, size=count).clip(40, 500)
            bwd_len_mean = np.random.normal(loc=60, scale=20, size=count).clip(0, 200)
            syn_flags = np.random.choice([1, 0], size=count, p=[0.9, 0.1])
            ack_flags = np.random.choice([0, 1], size=count, p=[0.8, 0.2])
            rst_flags = np.random.choice([0, 1], size=count, p=[0.85, 0.15])
            iat_mean = np.random.uniform(20, 300, size=count) # High frequency
            
        elif label == 'FTP-Patator':
            # Brute force on Port 21
            ports = np.full(count, 21)
            proto = np.full(count, 6)
            duration = np.random.normal(loc=45000, scale=12000, size=count).clip(5000, 150000)
            fwd_pkts = np.random.poisson(lam=6, size=count) + 3
            bwd_pkts = np.random.poisson(lam=7, size=count) + 3
            fwd_len_mean = np.random.normal(loc=75, scale=15, size=count).clip(30, 200)
            bwd_len_mean = np.random.normal(loc=95, scale=20, size=count).clip(40, 250)
            syn_flags = np.full(count, 1)
            ack_flags = np.full(count, 1)
            rst_flags = np.random.choice([0, 1], size=count, p=[0.7, 0.3])
            iat_mean = np.random.normal(loc=5000, scale=1500, size=count).clip(200, 20000)
            
        elif label == 'SSH-Patator':
            # Brute force on Port 22
            ports = np.full(count, 22)
            proto = np.full(count, 6)
            duration = np.random.normal(loc=75000, scale=25000, size=count).clip(10000, 250000)
            fwd_pkts = np.random.poisson(lam=18, size=count) + 8
            bwd_pkts = np.random.poisson(lam=22, size=count) + 10
            fwd_len_mean = np.random.normal(loc=320, scale=50, size=count).clip(100, 800)
            bwd_len_mean = np.random.normal(loc=480, scale=70, size=count).clip(150, 1100)
            syn_flags = np.full(count, 1)
            ack_flags = np.full(count, 1)
            rst_flags = np.random.choice([0, 1], size=count, p=[0.8, 0.2])
            iat_mean = np.random.normal(loc=3000, scale=800, size=count).clip(100, 15000)
            
        elif label == 'DoS-Hulk':
            # HTTP request flood on Port 80
            ports = np.full(count, 80)
            proto = np.full(count, 6)
            duration = np.random.exponential(scale=800000, size=count) + 30000
            fwd_pkts = np.random.poisson(lam=45, size=count) + 15
            bwd_pkts = np.random.poisson(lam=25, size=count) + 5
            fwd_len_mean = np.random.normal(loc=350, scale=90, size=count).clip(100, 900)
            bwd_len_mean = np.random.normal(loc=180, scale=40, size=count).clip(50, 500)
            syn_flags = np.random.choice([1, 0], size=count, p=[0.6, 0.4])
            ack_flags = np.full(count, 1)
            rst_flags = np.random.choice([0, 1], size=count, p=[0.9, 0.1])
            iat_mean = np.random.uniform(50, 1200, size=count)
            
        elif label == 'Web Attack - SQL Injection':
            # Exploitative payloads on Web server (80, 8080)
            ports = np.random.choice([80, 8080], size=count, p=[0.85, 0.15])
            proto = np.full(count, 6)
            duration = np.random.normal(loc=180000, scale=60000, size=count).clip(15000, 600000)
            fwd_pkts = np.random.poisson(lam=10, size=count) + 4
            bwd_pkts = np.random.poisson(lam=8, size=count) + 3
            # Injected payloads produce unusually high forward packet size variance
            fwd_len_mean = np.random.normal(loc=720, scale=180, size=count).clip(300, 1450)
            bwd_len_mean = np.random.normal(loc=540, scale=120, size=count).clip(150, 1200)
            syn_flags = np.full(count, 1)
            ack_flags = np.full(count, 1)
            rst_flags = np.random.choice([0, 1], size=count, p=[0.95, 0.05])
            iat_mean = np.random.normal(loc=15000, scale=4000, size=count).clip(1000, 50000)
            
        elif label == 'Botnet':
            # C2 beaconing on IRC/Custom ports
            ports = np.random.choice([6667, 8080, 8443, 9001], size=count, p=[0.4, 0.25, 0.2, 0.15])
            proto = np.full(count, 6)
            duration = np.random.normal(loc=350000, scale=50000, size=count).clip(80000, 800000)
            fwd_pkts = np.random.poisson(lam=7, size=count) + 2
            bwd_pkts = np.random.poisson(lam=7, size=count) + 2
            fwd_len_mean = np.random.normal(loc=140, scale=30, size=count).clip(40, 350)
            bwd_len_mean = np.random.normal(loc=160, scale=35, size=count).clip(40, 400)
            syn_flags = np.full(count, 1)
            ack_flags = np.full(count, 1)
            rst_flags = np.random.choice([0, 1], size=count, p=[0.98, 0.02])
            iat_mean = np.random.normal(loc=45000, scale=3000, size=count).clip(20000, 70000) # Highly periodic!
            
        # Compute derived network statistics
        tot_fwd_len = fwd_pkts * fwd_len_mean
        tot_bwd_len = bwd_pkts * bwd_len_mean
        tot_bytes = tot_fwd_len + tot_bwd_len
        tot_pkts = fwd_pkts + bwd_pkts
        
        # Microseconds to seconds for rate calculations
        dur_sec = np.maximum(duration / 1e6, 1e-6)
        flow_bytes_s = tot_bytes / dur_sec
        flow_pkts_s = tot_pkts / dur_sec
        
        avg_pkt_size = tot_bytes / tot_pkts
        down_up_ratio = np.round(bwd_pkts / np.maximum(fwd_pkts, 1), 2)
        
        df_class = pd.DataFrame({
            'Destination Port': ports.astype(int),
            'Flow Duration': np.round(duration, 2),
            'Total Fwd Packets': fwd_pkts.astype(int),
            'Total Backward Packets': bwd_pkts.astype(int),
            'Total Length of Fwd Packets': np.round(tot_fwd_len, 2),
            'Total Length of Bwd Packets': np.round(tot_bwd_len, 2),
            'Fwd Packet Length Mean': np.round(fwd_len_mean, 2),
            'Bwd Packet Length Mean': np.round(bwd_len_mean, 2),
            'Flow Bytes/s': np.round(flow_bytes_s, 2),
            'Flow Packets/s': np.round(flow_pkts_s, 2),
            'Flow IAT Mean': np.round(iat_mean, 2),
            'SYN Flag Count': syn_flags.astype(int),
            'ACK Flag Count': ack_flags.astype(int),
            'RST Flag Count': rst_flags.astype(int),
            'Average Packet Size': np.round(avg_pkt_size, 2),
            'Down/Up Ratio': down_up_ratio,
            'Protocol': proto.astype(int),
            'Label': label
        })
        dfs.append(df_class)
        
    df = pd.concat(dfs, ignore_index=True)
    # Shuffle records
    df = df.sample(frac=1.0, random_state=random_state).reset_index(drop=True)
    return df


def ensure_sample_data(filepath: str = None) -> str:
    """
    Ensure the synthetic network traffic dataset exists at the given filepath.
    If not, generates it and saves to disk.
    """
    if filepath is None:
        base_dir = os.path.dirname(os.path.abspath(__file__))
        filepath = os.path.join(base_dir, "sample_network_traffic.csv")
        
    os.makedirs(os.path.dirname(filepath), exist_ok=True)
    
    if not os.path.exists(filepath):
        df = generate_synthetic_network_data()
        df.to_csv(filepath, index=False)
        print(f"[+] Generated synthetic sample dataset: {filepath} ({len(df)} rows)")
    return filepath


if __name__ == "__main__":
    path = ensure_sample_data()
    print(f"Sample data generated successfully at {path}")
